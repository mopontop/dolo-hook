"""Bundle src/ into a single loadstring-able Luau file.

The bundle is a flat chunk: every module is registered as a factory function and
resolved through a tiny require shim, so the release file has no external
dependencies beyond Linoria (fetched at runtime).

Comment-only lines are dropped from the release. Executors differ in how large a
source string they will compile, and the readable copy always lives in src/.
"""

from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
OUT = ROOT / "release" / "dolo-hook.lua"
VERSION_FILE = SRC / "init.lua"

# Dependency order. A module may only require modules listed before it.
ORDER = [
    "util",
    "config",
    "features/player",
    "features/esp",
    "features/teleport",
    "features/misc",
    "features/draw",
    "features/targeting",
    "features/visuals",
    "features/world",
    "features/hud",
    "features/crosshair",
    "features/hitbox",
    "features/aim",
    "interface",
    "ui_fallback",
    "ui",
    "init",
]

COMMENT_LINE = re.compile(r"^\s*--(?!\[\[)")

HEADER = """--// Dolo.Hook — release bundle
--// generated by scripts/build.py — edit src/, never this file
--// version {version}
--// modules: {count}
--// sha256:  {digest}

local __modules = {{}}
local __cache = {{}}

local function __require(name)
	local cached = __cache[name]
	if cached ~= nil then
		return cached
	end
	local factory = __modules[name]
	if not factory then
		error(("module not found: %s"):format(name), 2)
	end
	local result = factory()
	__cache[name] = (result == nil) and true or result
	return __cache[name]
end
"""


def read(rel: str) -> str:
    path = SRC / f"{rel}.lua"
    if not path.is_file():
        raise SystemExit(f"missing module: {path}")
    return path.read_text(encoding="utf-8").rstrip() + "\n"


def module_version() -> str:
    text = VERSION_FILE.read_text(encoding="utf-8")
    match = re.search(r'local VERSION\s*=\s*"([^"]+)"', text)
    return match.group(1) if match else "0.0.0"


def strip_comment_lines(text: str) -> str:
    kept = [line.rstrip() for line in text.splitlines() if not COMMENT_LINE.match(line)]
    return "\n".join(kept) + "\n"


def build() -> tuple[str, int, int]:
    version = module_version()
    body: list[str] = []

    for name in ORDER:
        body.append(f'__modules["{name}"] = function()\n')
        body.append(read(name))
        body.append("end\n")

    body.append('return __require("init")\n')
    chunk = strip_comment_lines("".join(body))

    digest = hashlib.sha256(chunk.encode("utf-8")).hexdigest()
    header = HEADER.format(version=version, count=len(ORDER), digest=digest)
    return header + chunk, version, len(ORDER)


def main() -> int:
    bundle, version, count = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(bundle, encoding="utf-8", newline="\n")

    lines = bundle.count("\n")
    size = len(bundle.encode("utf-8"))
    print(f"built {OUT.relative_to(ROOT)}")
    print(f"  version {version} — {count} modules, {lines} lines, {size} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
